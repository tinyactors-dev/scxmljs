/**
 * Builds the browser bundles live mode loads, as COMMITTED files (the site copies prototypes/office
 * verbatim, with no build step of its own):
 *
 *   live/vendor/scxmljs.js   the library, trusted data model (packages/scxmljs/src/trusted.ts)
 *   live/vendor/tracer.js    the tracer (tracer/tracer.ts), importing ./scxmljs.js
 *   live/vendor/llm-chat.js  examples/llm-chat's system and charts (live/entries/llm-chat.ts)
 *   live/vendor/pi-durable.js  examples/pi-durable's system and charts (live/entries/pi-durable.ts)
 *   live/vendor/SOURCE-HASH  sha256 of every source file the bundles are made from
 *
 *   bun prototypes/office/live/build.ts           rebuild
 *   bun prototypes/office/live/build.ts --check   exit 1 when the bundles are stale (sources changed)
 *
 * Every bundle imports the library as "./scxmljs.js", so the page holds one copy of it: one
 * session registry, one VirtualClock class.
 */
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";

const here = new URL(".", import.meta.url).pathname;
const repo = join(here, "../../..");
const vendor = join(here, "vendor");
const check = process.argv.includes("--check");

const ENTRIES: { entry: string; out: string }[] = [
  { entry: join(repo, "packages/scxmljs/src/trusted.ts"), out: "scxmljs.js" },
  { entry: join(repo, "prototypes/office/tracer/tracer.ts"), out: "tracer.js" },
  { entry: join(here, "entries/llm-chat.ts"), out: "llm-chat.js" },
  { entry: join(here, "entries/pi-durable.ts"), out: "pi-durable.js" },
];
/** What the bundles are made from: a change in any of these makes them stale. */
const SOURCES = [
  "packages/scxmljs/src",
  "prototypes/office/tracer/tracer.ts",
  "prototypes/office/live/entries",
  "prototypes/office/live/build.ts",
  "examples/llm-chat/src",
  "examples/llm-chat/charts",
  "examples/pi-durable/src",
  "examples/pi-durable/charts",
];

async function walk(p: string): Promise<string[]> {
  try {
    const ents = await readdir(p, { withFileTypes: true });
    const out: string[] = [];
    for (const e of ents) out.push(...(e.isDirectory() ? await walk(join(p, e.name)) : [join(p, e.name)]));
    return out;
  } catch {
    return [p];
  }
}
async function sourceHash() {
  const files = (await Promise.all(SOURCES.map((s) => walk(join(repo, s))))).flat().filter((f) => !/node_modules|\.test\.ts$/.test(f)).sort();
  const h = createHash("sha256");
  for (const f of files) {
    h.update(relative(repo, f));
    h.update(await readFile(f));
  }
  return h.digest("hex");
}

const hash = await sourceHash();
const hashFile = join(vendor, "SOURCE-HASH");
if (check) {
  const old = (await readFile(hashFile, "utf8").catch(() => "")).trim();
  if (old !== hash) {
    console.error(`live/vendor is stale: its sources changed. Rebuild: bun prototypes/office/live/build.ts`);
    process.exit(1);
  }
  console.log("live/vendor is up to date");
  process.exit(0);
}

// the library is one shared module: every other bundle imports it as ./scxmljs.js
const shared = {
  name: "scxmljs-external",
  setup(b: { onResolve: (o: { filter: RegExp }, cb: (a: { path: string }) => unknown) => void }) {
    b.onResolve({ filter: /^@tinyactors\/scxmljs(\/trusted)?$/ }, () => ({ path: "./scxmljs.js", external: true }));
  },
};
for (const { entry, out } of ENTRIES) {
  const lib = out === "scxmljs.js";
  const r = await Bun.build({
    entrypoints: [entry],
    target: "browser",
    format: "esm",
    minify: true,
    sourcemap: "none",
    plugins: lib ? [] : [shared as never],
  });
  if (!r.success) {
    for (const m of r.logs) console.error(m);
    throw new Error(`live: bundling ${entry} failed`);
  }
  const text = `// GENERATED by prototypes/office/live/build.ts from ${relative(repo, entry)}: do not edit.\n${await r.outputs[0]!.text()}`;
  await writeFile(join(vendor, out), text);
  console.log(`${out}: ${(text.length / 1024).toFixed(1)} KB`);
}
await writeFile(hashFile, `${hash}\n`);
console.log(`SOURCE-HASH ${hash.slice(0, 12)}`);
